const fs = require("node:fs"), assert = require("node:assert/strict");
const plugin = fs.readFileSync(__dirname + "/yahoo-mail-ads.plugin", "utf8");
const rewrites = plugin.split("[Rewrite]")[1].split(/^\[/m)[0].split(/\r?\n/).filter((l) => l.startsWith("response if "));
assert.equal(rewrites.length, 2);
assert.ok(!/\[Argument\]|\[Script\]/.test(plugin));
const toRegex = (s) => new RegExp(s.slice(1, -1).replace(/\\\//g, "/"));
const urlOf = (line) => toRegex(/\$\{url\} ~= (\/.*?[^\\]\/) /.exec(line)[1]);

const [user, farm] = rewrites;
const userUrl = urlOf(user);
const [, re, rep] = /response\.body\.replace\((\/.*?[^\\]\/), ("(?:[^"\\]|\\.)*")\)/.exec(user);
const apply = (body) => body.replace(toRegex(re), JSON.parse(rep));
for (const u of ["https://appcscd.mail.yahooapis.jp/ws/v3/batch?ymappid=YahooMailIOSNativeApp", "https://appcscd.mail.yahooapis.jp/ws/v3/mailboxes/@.id==abc/attributes/@.id==userAttributes?appid=YahooMailIOSNativeApp"]) assert.ok(userUrl.test(u), u);
for (const u of ["https://appcscd.mail.yahooapis.jp/ws/v3/mailboxes/@.id==abc/messages/@.select==q", "https://appcscd.mail.yahooapis.jp.evil.test/ws/v3/batch", "http://appcscd.mail.yahooapis.jp/ws/v3/batch"]) assert.ok(!userUrl.test(u), u);
const attrs = JSON.stringify({result:{responses:[{id:"GETUserAttributes",response:{result:{value:{farm:8200,hasAds:true,isJPPremium:true}}}},{id:"Mail",response:{result:{text:"{\"hasAds\":true}"}}}]}});
const out = JSON.parse(apply(attrs));
assert.equal(out.result.responses[0].response.result.value.hasAds, false);
assert.equal(out.result.responses[0].response.result.value.isJPPremium, true);
assert.equal(out.result.responses[1].response.result.text, "{\"hasAds\":true}");
assert.equal(apply('{"hasAds" : true}'), '{"hasAds":false}');

const farmUrl = urlOf(farm);
for (const u of ["https://s.yimg.jp/dl/ymail/ios/ad-farm-v2.json", "https://s.yimg.jp/dl/ymail/ios/ad-farm-v2.json?v=1"]) assert.ok(farmUrl.test(u), u);
for (const u of ["https://s.yimg.jp/dl/ymail/ios/ad-farm-v2.jsonx", "https://s.yimg.jp.evil.test/dl/ymail/ios/ad-farm-v2.json", "https://s.yimg.jp/dl/ymail/android/ad-farm-v2.json"]) assert.ok(!farmUrl.test(u), u);
assert.ok(!/\$\{response\./.test(farm), "mock rewrite must not reference the response");
const mock = JSON.parse(/response\.body\.mock\("json", `([^`]*)`, 200\)/.exec(farm)[1]);
assert.deepEqual(Object.keys(mock), ["MessageList", "FolderList", "MessageDetail"]);
for (const v of Object.values(mock)) assert.deepEqual(v, {Farm: [], NGFarm: ["*", "8200"]});
assert.ok(farm.includes('response.header.set("Cache-Control", "no-store")'));
console.log("PASS: 2 rewrites, no script/argument, URL scope 5+6 cases, hasAds replace keeps escaped mail text, farm mock JSON");
